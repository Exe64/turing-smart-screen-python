def _resolve_credentials_path() -> Path:
    """Locate Claude Code's .credentials.json, honouring CLAUDE_CREDENTIALS and
    CLAUDE_CONFIG_DIR overrides before falling back to ~/.claude."""
    explicit = os.environ.get("CLAUDE_CREDENTIALS")
    if explicit:
        return Path(explicit)
    config_dir = os.environ.get("CLAUDE_CONFIG_DIR")
    if config_dir:
        return Path(config_dir) / ".credentials.json"
    return Path.home() / ".claude" / ".credentials.json"


CREDENTIALS_PATH = _resolve_credentials_path()
USAGE_API_URL = "https://api.anthropic.com/api/oauth/usage"
TOKEN_REFRESH_URL = "https://console.anthropic.com/v1/oauth/token"
# Claude Code's public OAuth client id, used for the refresh_token grant
OAUTH_CLIENT_ID = "9d1c250a-e61b-44d9-88ed-5944d1962f5e"


def _refresh_token(oauth: dict) -> Optional[dict]:
    """Refresh an expired access token using the refresh token, and persist the
    new tokens back to the credentials file so Claude Code stays in sync."""
    refresh = oauth.get("refreshToken")
    if not refresh:
        return None
    try:
        resp = requests.post(
            TOKEN_REFRESH_URL,
            json={
                "grant_type": "refresh_token",
                "refresh_token": refresh,
                "client_id": OAUTH_CLIENT_ID,
            },
            timeout=10,
        )
        resp.raise_for_status()
        data = resp.json()
        oauth["accessToken"] = data["access_token"]
        if data.get("refresh_token"):
            oauth["refreshToken"] = data["refresh_token"]
        if data.get("expires_in"):
            oauth["expiresAt"] = int((time.time() + data["expires_in"]) * 1000)
        try:
            with open(CREDENTIALS_PATH) as f:
                creds = json.load(f)
            if "claudeAiOauth" in creds:
                creds["claudeAiOauth"].update(oauth)
                with open(CREDENTIALS_PATH, "w") as f:
                    json.dump(creds, f)
        except Exception as e:
            logger.warning("Could not persist refreshed token: %s", e)
        logger.info("Claude OAuth token refreshed")
        return oauth
    except Exception as e:
        logger.warning("Failed to refresh Claude OAuth token: %s", e)
        return None


def _oauth_from_env() -> Optional[dict]:
    """Use a long-lived OAuth token from CLAUDE_CODE_OAUTH_TOKEN (generated by
    `claude setup-token`) if present. This is the supported way to authenticate
    an external script."""
    token = os.environ.get("CLAUDE_CODE_OAUTH_TOKEN")
    if token:
        return {"accessToken": token}
    return None


def _find_oauth(obj) -> Optional[dict]:
    """Recursively look for a Claude OAuth block (claudeAiOauth.accessToken)."""
    if isinstance(obj, dict):
        oauth = obj.get("claudeAiOauth")
        if isinstance(oauth, dict) and oauth.get("accessToken"):
            return oauth
        for value in obj.values():
            found = _find_oauth(value)
            if found:
                return found
    elif isinstance(obj, list):
        for value in obj:
            found = _find_oauth(value)
            if found:
                return found
    return None


def _oauth_from_file() -> Optional[dict]:
    """Read the Claude OAuth block from the .credentials.json file (Linux/macOS)."""
    try:
        with open(CREDENTIALS_PATH) as f:
            return _find_oauth(json.load(f))
    except Exception:
        return None


def _oauth_from_windows_credential_manager() -> Optional[dict]:
    """Read the Claude OAuth block from the Windows Credential Manager.

    On Windows, Claude Code stores its primary credentials in the Credential
    Manager (the .credentials.json file only holds MCP plugin tokens).
    """
    if sys.platform != "win32":
        return None
    try:
        import win32cred  # provided by pywin32 (Windows requirement)
    except ImportError:
        logger.warning("pywin32 not installed: cannot read Windows Credential Manager")
        return None
    try:
        entries = win32cred.CredEnumerate(None, 0)
    except Exception as e:
        logger.warning("Failed to enumerate Windows credentials: %s", e)
        return None
    for cred in entries:
        target = (cred.get("TargetName") or "").lower()
        if "claude" not in target:
            continue
        blob = cred.get("CredentialBlob")
        if not blob:
            continue
        text = None
        if isinstance(blob, bytes):
            for encoding in ("utf-16-le", "utf-8"):
                try:
                    text = blob.decode(encoding)
                    break
                except UnicodeDecodeError:
                    continue
        elif isinstance(blob, str):
            text = blob
        if not text:
            continue
        try:
            data = json.loads(text)
        except Exception:
            continue
        oauth = _find_oauth(data)
        if oauth:
            return oauth
    return None


def get_claude_oauth() -> Optional[dict]:
    """Return the Claude OAuth block.

    The subscription-login token (credentials file / Windows Credential Manager)
    is preferred because it carries the 'user:profile' scope required by the
    usage endpoint. The CLAUDE_CODE_OAUTH_TOKEN env var (from `claude
    setup-token`) is only an inference-scoped fallback and does not work with the
    usage API, so it is tried last."""
    return (
        _oauth_from_file()
        or _oauth_from_windows_credential_manager()
        or _oauth_from_env()
    )


class _ClaudeUsageCache:
    """Shared cache for Claude API usage data, refreshed at most every minute.

    On error, an exponential backoff (up to 30 minutes) prevents hammering the
    API and triggering Cloudflare rate limiting. An expired token is refreshed
    proactively (the usage API can answer 429 instead of 401 on an expired
    token, which would bypass a refresh-on-401-only strategy). When the refresh
    token itself is dead (invalid_grant), auth_expired() turns True so sensors
    can show a re-login prompt instead of silent zeros."""

    _data: Optional[dict] = None
    _last_fetch: float = 0
    _ttl: float = 60
    _backoff: float = 0
    _next_retry: float = 0
    _auth_expired: bool = False

    @classmethod
    def auth_expired(cls) -> bool:
        """True when the stored credentials are dead and an interactive
        `claude` login is required."""
        return cls._auth_expired

    @classmethod
    def _fetch(cls, token: str) -> "requests.Response":
        return requests.get(
            USAGE_API_URL,
            headers={"Authorization": f"Bearer {token}"},
            timeout=10,
        )

    @classmethod
    def get(cls) -> Optional[dict]:
        now = time.time()
        if cls._data is not None and (now - cls._last_fetch) < cls._ttl:
            return cls._data
        if now < cls._next_retry:
            return cls._data if cls._data is not None else {}
        try:
            oauth = get_claude_oauth()
            if not oauth:
                raise RuntimeError("Claude OAuth credentials not found")
            # Proactive refresh: never call the usage API with a token known to
            # be expired, and don't rely on a 401 to trigger the refresh.
            expires_at = oauth.get("expiresAt")
            if expires_at and expires_at / 1000 <= now:
                refreshed = _refresh_token(oauth)
                if not refreshed:
                    cls._auth_expired = True
                    raise RuntimeError(
                        "Claude OAuth token expired and refresh failed: "
                        "run `claude` in a terminal and log in again"
                    )
                oauth = refreshed
            resp = cls._fetch(oauth["accessToken"])
            if resp.status_code == 401:
                refreshed = _refresh_token(oauth)
                if not refreshed:
                    cls._auth_expired = True
                else:
                    resp = cls._fetch(refreshed["accessToken"])
            if resp.status_code == 429:
                retry_after = float(resp.headers.get("Retry-After", 300))
                cls._next_retry = now + retry_after
                logger.warning("Claude usage API rate limited, retry in %ds", retry_after)
                return cls._data if cls._data is not None else {}
            resp.raise_for_status()
            cls._data = resp.json()
            cls._last_fetch = now
            cls._backoff = 0
            cls._next_retry = 0
            cls._auth_expired = False
        except Exception as e:
            logger.warning("Failed to fetch Claude usage: %s", e)
            if cls._auth_expired:
                # Fixed 5-minute retry so a re-login is picked up quickly
                # (each retry only hits the cheap token refresh endpoint)
                cls._next_retry = now + 300
            else:
                cls._backoff = min(max(cls._backoff * 2, 120), 1800)
                cls._next_retry = now + cls._backoff
            if cls._data is None:
                cls._data = {}
        return cls._data


# Custom data classes must be implemented in this file, inherit the CustomDataSource and implement its 2 methods
class CustomDataSource(ABC):
    @abstractmethod
    def as_numeric(self) -> float:
        # Numeric value will be used for graph and radial progress bars
        # If there is no numeric value, keep this function empty
        pass

    @abstractmethod
    def as_string(self) -> str:
        # Text value will be used for text display and radial progress bar inner text
        # Numeric value can be formatted here to be displayed as expected
        # It is also possible to return a text unrelated to the numeric value
        # If this function is empty, the numeric value will be used as string without formatting
        pass

    @abstractmethod
    def last_values(self) -> List[float]:
        # List of last numeric values will be used for plot graph
        # If you do not want to draw a line graph or if your custom data has no numeric values, keep this function empty
        pass


# Example for a custom data class that has numeric and text values
class ExampleCustomNumericData(CustomDataSource):
    # This list is used to store the last 10 values to display a line graph
    last_val = [math.nan] * 10  # By default, it is filed with math.nan values to indicate there is no data stored

    def as_numeric(self) -> float:
        # Numeric value will be used for graph and radial progress bars
        # Here a Python function from another module can be called to get data
        # Example: self.value = my_module.get_rgb_led_brightness() / audio.system_volume() ...
        self.value = 75.845

        # Store the value to the history list that will be used for line graph
        self.last_val.append(self.value)
        # Also remove the oldest value from history list
        self.last_val.pop(0)

        return self.value

    def as_string(self) -> str:
        # Text value will be used for text display and radial progress bar inner text.
        # Numeric value can be formatted here to be displayed as expected
        # It is also possible to return a text unrelated to the numeric value
        # If this function is empty, the numeric value will be used as string without formatting
        # Example here: format numeric value: add unit as a suffix, and keep 1 digit decimal precision
        return f'{self.value:>5.1f}%'
        # Important note! If your numeric value can vary in size, be sure to display it with a default size.
        # E.g. if your value can range from 0 to 9999, you need to display it with at least 4 characters every time.
        # --> return f'{self.as_numeric():>4}%'
        # Otherwise, part of the previous value can stay displayed ("ghosting") after a refresh

    def last_values(self) -> List[float]:
        # List of last numeric values will be used for plot graph
        return self.last_val


# Example for a custom data class that only has text values
class ExampleCustomTextOnlyData(CustomDataSource):
    def as_numeric(self) -> float:
        # If there is no numeric value, keep this function empty
        pass

    def as_string(self) -> str:
        # If a custom data class only has text values, it won't be possible to display graph or radial bars
        return "Python: " + platform.python_version()

    def last_values(self) -> List[float]:
        # If a custom data class only has text values, it won't be possible to display line graph
        pass


class ClaudeFiveHourUsage(CustomDataSource):
    last_val = [math.nan] * 20

    def as_numeric(self) -> float:
        data = _ClaudeUsageCache.get()
        self.value = 0.0
        self.resets_at = ""
        if data and "five_hour" in data and data["five_hour"]:
            self.value = float(data["five_hour"].get("utilization", 0) or 0)
            raw_reset = data["five_hour"].get("resets_at", "")
            if raw_reset:
                try:
                    dt = datetime.fromisoformat(raw_reset)
                    self.resets_at = dt.strftime("%H:%M")
                except Exception:
                    self.resets_at = ""
        self.last_val.append(self.value)
        self.last_val.pop(0)
        return self.value

    def as_string(self) -> str:
        if _ClaudeUsageCache.auth_expired():
            return "LOGIN!"
        return f'{self.value:>5.1f}%'

    def last_values(self) -> List[float]:
        return self.last_val


